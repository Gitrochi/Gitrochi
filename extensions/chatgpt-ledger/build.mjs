import { readFile, writeFile } from "node:fs/promises";
import { extractQuestion } from "./extractor.js";
import { canonicalConversation } from "./protocol.js";

const runtime = await readFile(new URL("content.js", import.meta.url), "utf8");
const output = `// Generated by build.mjs. Edit extractor.js, protocol.js or content.js.\n(() => {\n${extractQuestion.toString()}\n${canonicalConversation.toString()}\n${runtime}\n})();\n`;
const target = new URL("content-bundle.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(target, "utf8").catch(() => "") !== output) {
    process.stderr.write("The content bundle is stale. Run npm run build.\n");
    process.exitCode = 1;
  }
} else {
  await writeFile(target, output);
}
