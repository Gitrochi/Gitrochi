import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
// 시스템 Rust를 바꾸지 않고 준비한 프로젝트 전용 툴체인도 사용할 수 있다.
const host = `${process.arch === "arm64" ? "aarch64" : "x86_64"}-${process.platform === "darwin" ? "apple-darwin" : process.platform === "win32" ? "pc-windows-msvc" : "unknown-linux-gnu"}`;
const localRoot = path.join(root, ".build/rust-tools");
const localBin = path.join(localRoot, "rustup/toolchains", `stable-${host}`, "bin");
const localProxy = path.join(localRoot, "cargo/bin");
const useLocal = !process.env.GITROCHI_CARGO && existsSync(path.join(localBin, "cargo")) && existsSync(path.join(localProxy, "cargo"));
const cargo = process.env.GITROCHI_CARGO || (useLocal ? path.join(localProxy, "cargo") : "cargo");
const buildEnv = { ...process.env, ...(useLocal ? { RUSTUP_HOME: path.join(localRoot, "rustup"), PATH: localProxy + path.delimiter + process.env.PATH } : {}) };
if (process.platform === "darwin") {
  buildEnv.MACOSX_DEPLOYMENT_TARGET ??= "15.0";
  if (useLocal) buildEnv.DYLD_LIBRARY_PATH = path.join(localBin, "../lib") + (process.env.DYLD_LIBRARY_PATH ? path.delimiter + process.env.DYLD_LIBRARY_PATH : "");
}
const build = spawnSync(cargo, ["build", "--locked", "--release", "--lib", "--manifest-path", path.join(root,"crates/Cargo.toml"), "--target", "wasm32-unknown-unknown"], { cwd: root, stdio: "inherit", env: buildEnv });
if (build.error || build.status !== 0) {
  console.error("Build the shared core with Rust stable and the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown).");
  process.exit(build.status || 1);
}
const bytes = readFileSync(path.join(root,"crates/target/wasm32-unknown-unknown/release/gitrochi_core.wasm"));
// 외부 URL·런타임 다운로드 없이 앱·worker·Node 검사에서 똑같은 모듈을 초기화한다.
const output = `// Generated by tools/build-core.mjs; do not edit.\nexport const coreBytes = "${bytes.toString("base64")}";\n`;
const target = path.join(root,"windows/src/shared/core/core.generated.ts");
let previous; try { previous=readFileSync(target,"utf8"); } catch {}
if (previous !== output) writeFileSync(target,output);

// 같은 Rust 패키지의 네이티브 실행 파일도 CLI 리소스로 배포한다.
const native = spawnSync(cargo, ["build", "--locked", "--release", "--bin", "gitch-core", "--bin", "gitrochi-index", "--manifest-path", path.join(root,"crates/Cargo.toml")], { cwd: root, stdio: "inherit", env: buildEnv });
if (native.error || native.status !== 0) process.exit(native.status || 1);

const nativeSource = path.join(root, "crates/target/release", process.platform === "win32" ? "gitch-core.exe" : "gitch-core");
const nativeDirectory = path.join(root, "windows/src-tauri/generated");
mkdirSync(nativeDirectory, { recursive: true });
copyFileSync(nativeSource, path.join(nativeDirectory, "gitch-core.exe"));
// The repository index CLI for gitch, the Python tools and the Go monitor (the app links the crate).
copyFileSync(path.join(root, "crates/target/release", process.platform === "win32" ? "gitrochi-index.exe" : "gitrochi-index"), path.join(nativeDirectory, "gitrochi-index.exe"));

// The Ledger CLI and MCP server for agents (the app links the crate). A build of its own keeps the two above exactly as
// they were: in one build, cargo would give their SQLite the ledger's extra features.
const ledger = spawnSync(cargo, ["build", "--locked", "--release", "--bin", "gitrochi-ledger", "--manifest-path", path.join(root,"crates/Cargo.toml")], { cwd: root, stdio: "inherit", env: buildEnv });
if (ledger.error || ledger.status !== 0) process.exit(ledger.status || 1);
copyFileSync(path.join(root, "crates/target/release", process.platform === "win32" ? "gitrochi-ledger.exe" : "gitrochi-ledger"), path.join(nativeDirectory, "gitrochi-ledger.exe"));
