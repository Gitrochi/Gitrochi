#!/usr/bin/env python3
"""Collect exact locked normal/build dependency notices for every flow target."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
from urllib.parse import quote


def dependencies(metadata):
    """Walk normal/build edges only, including platform-specific dependencies."""
    resolve = metadata["resolve"]
    root = resolve["root"]
    if not root:
        raise ValueError("Cargo metadata did not identify the flow package")
    nodes = {node["id"]: node for node in resolve["nodes"]}
    seen = {root}
    pending = [root]
    while pending:
        for dependency in nodes[pending.pop()]["deps"]:
            if not any(kind["kind"] in (None, "build") for kind in dependency["dep_kinds"]):
                continue
            identifier = dependency["pkg"]
            if identifier not in seen:
                seen.add(identifier)
                pending.append(identifier)
    packages = {package["id"]: package for package in metadata["packages"]}
    return packages[root], sorted(
        (packages[identifier] for identifier in seen - {root}),
        key=lambda package: (package["name"], package["version"]),
    )


def render(metadata, supplements=None):
    root, packages = dependencies(metadata)
    if supplements is None:
        supplements = json.loads(Path(__file__).with_name("supplemental-notices.json").read_text())
    inventory = []
    texts = {}
    for package in packages:
        name, version = package["name"], package["version"]
        if package["source"] != "registry+https://github.com/rust-lang/crates.io-index":
            raise ValueError(f"Unreviewed dependency source: {name} {version}")
        directory = Path(package["manifest_path"]).parent.resolve()
        paths = {
            path for path in directory.rglob("*")
            if path.is_file() and path.name.upper().startswith(("LICENSE", "COPYING", "NOTICE", "COPYRIGHT"))
        }
        if package.get("license_file"):
            paths.add(directory / package["license_file"])
        source = f"https://static.crates.io/crates/{quote(name)}/{quote(name)}-{quote(version)}.crate"
        entries = []
        files = []
        for path in sorted(paths):
            relative = path.resolve().relative_to(directory).as_posix()
            data = path.read_bytes()
            files.append((relative, data))
        for supplement in supplements:
            if (name, version) != (supplement["package"], supplement["version"]):
                continue
            if package.get("license") != supplement["declared_license"]:
                raise ValueError(f"Changed supplemental license expression: {name} {version}")
            path = Path(__file__).parent / supplement["path"]
            data = path.read_bytes()
            if hashlib.sha256(data).hexdigest() != supplement["sha256"]:
                raise ValueError(f"Changed supplemental license text: {name} {version}")
            relative = f"{path.name} (selected {supplement['selected_license']} option)"
            entries.append(f"  Supplemental source: {supplement['url']}\n  License declaration: {supplement['declaration_source']}\n  Reason: {supplement['reason']}")
            files.append((relative, data))
        if not files:
            raise ValueError(f"No upstream license/notice files: {name} {version}")
        for relative, data in files:
            if not data.strip():
                raise ValueError(f"Empty upstream notice: {name} {version}/{relative}")
            content = data.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
            digest = hashlib.sha256(data).hexdigest()
            reference = f"{name} {version}/{relative}"
            texts.setdefault(digest, {"content": content, "references": []})["references"].append(reference)
            entries.append(f"  {relative}: SHA256 {digest}")
        license_expression = package.get("license") or "see upstream license file"
        authors = "; ".join(package.get("authors", [])) or "not provided"
        inventory.append(f"{name} {version}\nLicense expression: {license_expression}\nAuthors: {authors}\nSource: {source}\n" + "\n".join(entries))

    sections = [
        f"gitch-flow {root['version']} — third-party dependency notices",
        "Generated by tools/gitch-flow/ci/generate-notices.py from cargo metadata --locked.\n"
        "Scope: all target platforms; transitive normal and build dependencies; excludes the root package and dev-only dependencies.\n"
        "Upstream wording and copyright notices are preserved. Output uses LF, removes trailing spaces/tabs, and ends with one LF.\n"
        "Identical complete upstream files share one text below.\n"
        "File SHA256 values identify original upstream bytes before line-ending normalization.\n"
        "These dependency licenses do not change the terms of Gitrochi's own code; see the repository LICENSE or the app's LICENSE.txt.\n"
        f"https://github.com/Gitrochi/Gitrochi/blob/v{root['version']}/LICENSE\n"
        f"Coverage: {len(packages)} dependency packages; {len(texts)} distinct upstream files.",
        "DEPENDENCY INVENTORY\n\n" + "\n\n".join(inventory),
        "UPSTREAM LICENSE AND NOTICE TEXTS",
    ]
    for digest, entry in sorted(texts.items(), key=lambda item: item[1]["references"][0]):
        sections.append("=" * 78 + "\n" + "\n".join(entry["references"]) + f"\nSHA256 {digest}\n" + "=" * 78 + "\n" + entry["content"])
    lines = (line.rstrip(" \t") for line in "\n\n".join(sections).split("\n"))
    result = ("\n".join(lines).rstrip("\n") + "\n").encode("utf-8")
    if len(result) >= 2_000_000:
        raise ValueError("Notice bundle exceeds 2 MB")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in bundle needs regeneration")
    arguments = parser.parse_args()
    directory = Path(__file__).resolve().parent.parent
    metadata = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--manifest-path", str(directory / "Cargo.toml")],
        check=True, stdout=subprocess.PIPE,
    )
    content = render(json.loads(metadata.stdout))
    output = directory / "THIRD_PARTY_NOTICES.txt"
    if arguments.check:
        if not output.is_file() or output.read_bytes() != content:
            raise ValueError("Flow notices are stale; run python3 tools/gitch-flow/ci/generate-notices.py")
        print(f"Flow dependency notices are current ({len(content)} bytes)")
    else:
        output.write_bytes(content)
        print(f"Wrote {output.name} ({len(content)} bytes)")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"Flow dependency notices: {error}", file=sys.stderr)
        sys.exit(1)
