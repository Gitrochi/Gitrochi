//! `gitch flow export github|gitlab|jenkins`: writes a thin configuration that runs the same flow on a CI runner.
//! It downloads a pinned gitch, runs `gitch flow run <flow> --ci` and uploads the result contract (gitch-flow-out/).
//! Existing CI files are not changed, and a different file at the same path is not overwritten without --force.

use crate::cli::{Args, Out};
use crate::util::tr;
use serde_json::json;
use std::path::Path;

fn install_lines(ver: &str) -> Vec<String> {
    let url = std::env::var("GITCH_INSTALL_URL").unwrap_or_else(|_| {
        format!("https://raw.githubusercontent.com/Gitrochi/Gitrochi/v{ver}/tools/gitch/install.sh")
    });
    vec![
        "command -v curl >/dev/null 2>&1 || (apt-get update -qq && apt-get install -y -qq curl ca-certificates git >/dev/null)".into(),
        format!("curl -fsSL {url} | GITCH_VERSION={ver} bash"),
    ]
}

/// Picks the CI image from what project detection found (for GitLab and Jenkins docker agents).
fn guess_image(root: &Path) -> &'static str {
    if root.join("package.json").is_file() {
        "node:22"
    } else if root.join("pyproject.toml").is_file() || root.join("requirements.txt").is_file() {
        "python:3.12"
    } else if root.join("go.mod").is_file() {
        "golang:1.23"
    } else if root.join("Cargo.toml").is_file() {
        "rust:1"
    } else if root.join("pom.xml").is_file()
        || root.join("build.gradle").is_file()
        || root.join("build.gradle.kts").is_file()
    {
        "eclipse-temurin:21"
    } else {
        "ubuntu:24.04"
    }
}

pub fn github(flow: &str, ver: &str, runs_on: &str, on_push: bool) -> String {
    let install = install_lines(ver);
    format!(
        "# {note}
name: gitch flow {flow}
run-name: \"gitch flow {flow}${{{{ inputs.gitch_flow_corr && format(' [{{0}}]', inputs.gitch_flow_corr) || '' }}}}\"
on:
{push}  pull_request:
  workflow_dispatch:
    inputs:
      gitch_flow_corr:
        description: gitch flow correlation id (set by gitch when it triggers this workflow)
        required: false
        default: \"\"
concurrency:
  group: gitch-flow-{flow}-${{{{ github.ref }}}}
  cancel-in-progress: false
jobs:
  flow:
    runs-on: {runs_on}
    timeout-minutes: 60
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - name: Install gitch {ver}
        run: |
          {i0}
          {i1}
          echo \"$HOME/.local/share/gitch\" >> \"$GITHUB_PATH\"
      - name: gitch flow run {flow}
        run: gitch flow run {flow} --ci
      - name: Upload the result contract
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: gitch-flow-out
          path: gitch-flow-out/
          if-no-files-found: warn
",
        note = tr("gitch flow export 가 만든 파일입니다. 흐름 정의는 .gitch/flow.yml 에 있습니다.", "Generated by gitch flow export. The flow itself lives in .gitch/flow.yml."),
        push = if on_push { "  push:\n    branches: [main]\n" } else { "" },
        i0 = install[0],
        i1 = install[1],
    )
}

pub fn gitlab(flow: &str, ver: &str, image: &str) -> String {
    let install = install_lines(ver);
    format!(
        "# {note}
# {include}
gitch-flow-{flow}:
  stage: test
  image: {image}
  variables:
    GIT_DEPTH: \"0\"
    GITCH_FLOW_CORR: \"\"
  before_script:
    - {i0}
    - {i1}
    - export PATH=\"$HOME/.local/share/gitch:$PATH\"
  script:
    - gitch flow run {flow} --ci
  artifacts:
    when: always
    paths:
      - gitch-flow-out/
    reports:
      junit: gitch-flow-out/junit.xml
",
        note = tr(
            "gitch flow export 가 만든 파일입니다.",
            "Generated by gitch flow export."
        ),
        include = tr(
            "기존 .gitlab-ci.yml 에 다음을 더하세요: include: [{ local: .gitlab-ci.gitch.yml }]",
            "Add this to your .gitlab-ci.yml: include: [{ local: .gitlab-ci.gitch.yml }]"
        ),
        i0 = install[0].replace('"', "\\\""),
        i1 = install[1],
    )
}

pub fn jenkins(flow: &str, ver: &str) -> String {
    let install = install_lines(ver);
    format!(
        "// {note}
pipeline {{
  agent any
  parameters {{
    string(name: 'GITCH_FLOW_CORR', defaultValue: '', description: 'gitch flow correlation id (set by gitch when it triggers this job)')
  }}
  options {{
    timeout(time: 60, unit: 'MINUTES')
    disableConcurrentBuilds()
  }}
  stages {{
    stage('gitch flow {flow}') {{
      steps {{
        sh '''
          {i0}
          {i1}
          export PATH=\"$HOME/.local/share/gitch:$PATH\"
          gitch flow run {flow} --ci
        '''
      }}
    }}
  }}
  post {{
    always {{
      junit allowEmptyResults: true, testResults: 'gitch-flow-out/junit.xml'
      archiveArtifacts artifacts: 'gitch-flow-out/**', allowEmptyArchive: true
    }}
  }}
}}
",
        note = tr("gitch flow export 가 만든 파일입니다.", "Generated by gitch flow export."),
        i0 = install[0],
        i1 = install[1],
    )
}

pub fn cmd_export(out: &Out, args: &Args) -> i32 {
    let Some(target) = args.pos.first().cloned() else {
        eprintln!(
            "{}",
            tr(
                "대상이 필요합니다: github · gitlab · jenkins",
                "a target is required: github, gitlab, jenkins"
            )
        );
        return 1;
    };
    let spec = match crate::spec::load(&crate::cli::repo_root(args).unwrap_or_default()) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("{}", e[0].human());
            return 1;
        }
    };
    let flow = args
        .val("--flow")
        .or_else(|| {
            spec.flows
                .iter()
                .find(|f| f.trigger.iter().any(|t| t == "ci"))
                .map(|f| f.name.clone())
        })
        .or_else(|| spec.flows.first().map(|f| f.name.clone()))
        .unwrap_or_else(|| "full".into());
    if spec.flow(&flow).is_none() {
        eprintln!("{}", crate::codes::line("PLAN-01"));
        return 1;
    }
    let ver = env!("CARGO_PKG_VERSION");
    let (text, default_path) = match target.as_str() {
        "github" => (
            github(
                &flow,
                ver,
                &args
                    .val("--runs-on")
                    .unwrap_or_else(|| "ubuntu-latest".into()),
                spec.flow(&flow)
                    .map(|f| f.trigger.iter().any(|t| t == "ci"))
                    .unwrap_or(false),
            ),
            format!(".github/workflows/gitch-{flow}.yml"),
        ),
        "gitlab" => (
            gitlab(
                &flow,
                ver,
                &args
                    .val("--image")
                    .unwrap_or_else(|| guess_image(&spec.root).into()),
            ),
            ".gitlab-ci.gitch.yml".to_string(),
        ),
        "jenkins" => (jenkins(&flow, ver), "Jenkinsfile.gitch".to_string()),
        other => {
            eprintln!(
                "{}",
                tr(
                    &format!("모르는 대상: {other}"),
                    &format!("unknown target: {other}")
                )
            );
            return 1;
        }
    };
    let rel = args.val("--out").unwrap_or(default_path);
    let path = spec.root.join(&rel);
    let existing = std::fs::read_to_string(&path).ok();
    let same = existing.as_deref() == Some(text.as_str());
    let dry = args.has("--dry-run");
    let mut written = false;
    if !dry && !same {
        if existing.is_some() && !args.has("--force") {
            eprintln!("{}", tr(&format!("{rel} 에 다른 내용이 있어 쓰지 않았습니다(--dry-run 으로 보고 --force 로 바꾸기)."), &format!("{rel} already has different content and was not changed (see --dry-run, replace with --force).")));
            return 1;
        }
        if let Err(e) = crate::util::write_atomic(&path, text.as_bytes()) {
            eprintln!("{e}");
            return 1;
        }
        written = true;
    }
    if out.json {
        println!("{}", serde_json::to_string_pretty(&json!({"schemaVersion": 1, "target": target, "flow": flow, "path": rel, "written": written, "unchanged": same, "content": text})).unwrap_or_default());
    } else if dry {
        print!("{text}");
    } else if same {
        println!(
            "{}",
            tr(
                &format!("{rel} 는 이미 최신입니다."),
                &format!("{rel} is already up to date.")
            )
        );
    } else {
        println!(
            "{}",
            tr(
                &format!("✔ {rel} 을(를) 만들었습니다. 확인한 뒤 커밋하세요."),
                &format!("✔ wrote {rel}. Review it, then commit it.")
            )
        );
    }
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_files_parse() {
        let gh = github("full", "0.3.12", "ubuntu-latest", true);
        let v = crate::yaml::parse(&gh).expect("github yaml");
        assert_eq!(
            v.value["jobs"]["flow"]["steps"][2]["run"],
            "gitch flow run full --ci"
        );
        assert!(v.value["on"]["workflow_dispatch"]["inputs"]["gitch_flow_corr"].is_object());
        let gl = gitlab("full", "0.3.12", "node:22");
        let g = crate::yaml::parse(&gl).expect("gitlab yaml");
        assert_eq!(
            g.value["gitch-flow-full"]["artifacts"]["reports"]["junit"],
            "gitch-flow-out/junit.xml"
        );
        let j = jenkins("full", "0.3.12");
        assert!(j.contains("gitch flow run full --ci") && j.contains("GITCH_FLOW_CORR"));
    }
}
